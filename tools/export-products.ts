// Writes supabase/products.sql: the catalog's prices and opening stock, so the server can check unit prices
// and keep real stock. Prices are refreshed on every run; stock is only set for new products.
//   npx vite-node tools/export-products.ts
import { writeFileSync } from 'node:fs';
import { PRODUCTS } from '@/data/products';

const esc = (s: string) => s.replace(/'/g, "''");
const rows = PRODUCTS.map((p) => `(${p.id}, '${esc(p.name)}', ${p.price}, ${p.stock})`).join(',\n');
const sql = `-- generated by tools/export-products.ts — do not edit by hand
create table if not exists public.products (
  id     integer primary key,
  name   text not null,
  price  integer not null check (price > 0),
  stock  integer not null check (stock >= 0)
);
alter table public.products enable row level security;
drop policy if exists "read products" on public.products;
create policy "read products" on public.products for select to anon, authenticated using (true);
grant select on public.products to anon, authenticated;

insert into public.products (id, name, price, stock) values
${rows}
on conflict (id) do update set name = excluded.name, price = excluded.price;
`;
writeFileSync('supabase/products.sql', sql);
console.log(`products.sql: ${PRODUCTS.length} products`);
